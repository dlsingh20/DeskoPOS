import { downloadXlsx } from '../../utils/xlsxWriter';
import {
  ORDER_TYPE_LABELS,
  PENDING_CATEGORY_LABELS,
  describePayments,
  formatDateTime,
  getItemLineAmount,
  getItemsTotal,
  getPaymentLabel,
  getPaymentReference,
  groupItemsByRound,
  money,
  reconcileSummary,
} from '../../utils/historyUtils';

const plainAmount = (value) => (Number(value) || 0).toFixed(2);

/**
 * Builds the workbook sheets for the bills currently shown (same tab, filters and date range).
 * Amounts are numbers so Excel totals match the summary cards.
 */
export const buildHistorySheets = ({ bills, summary, meta, timeZone, staffName, itemCategory }) => {
  const reportInfo = [
    { cells: ['Report', meta.tabLabel], style: 'header' },
    ['Restaurant', meta.restaurantName || ''],
    ['Date range', meta.rangeLabel],
    ['Time zone', timeZone],
    ['Filters', meta.filterLabel || 'None'],
    ['Generated at', formatDateTime(new Date().toISOString(), timeZone)],
    ['Generated by', meta.operatorName || ''],
    [],
    { cells: ['Summary', 'Value'], style: 'header' },
    ['Bills', summary.bills],
    ['Billable bills (completed + credit)', summary.billable],
    ['Total', summary.total],
    ['Cash', summary.cash],
    ['Card', summary.card],
    ['UPI / wallets', summary.upi],
    ['Guest Visit (room charge)', summary.guestVisit],
    ['Other methods', summary.other],
    ['Pending Collection', summary.pendingCollection],
    ['Written off / settled outside POS', summary.writtenOff],
    ['Overpaid', summary.overpaid],
    ['Tax', summary.tax],
    ['Discount', summary.discount],
    ['Charges', summary.charges],
    ['Cancelled bills', summary.cancelledCount],
    ['Cancelled value (not in Total)', summary.cancelledValue],
    ['Refunded bills', summary.refundedCount],
    ['Refunded value (not in Total)', summary.refundedValue],
    ['Part refunds on completed bills (in Total)', summary.partRefunds],
    ['Reconciliation difference', reconcileSummary(summary)],
    [],
    ['Note', 'Total = Cash + Card + UPI + Guest Visit + Other + Pending Collection + Written off - Overpaid. Cancelled and refunded bills are excluded from Total, Tax and payment totals.'],
    ['Note', 'Closed time is the last completed payment, or the last update when there is none (the API has no closed-at field).'],
  ];

  const summaryRows = [
    {
      cells: ['Bill No', 'Status', 'Pending category', 'Order type', 'Table', 'Customer', 'Mobile', 'Total', 'Payment',
        'Paid', 'Balance due', 'Tax', 'Discount', 'Charges', 'Subtotal', 'Order time', 'Closed', 'Server', 'Settled by'],
      style: 'header',
    },
    ...bills.map((bill) => [
      bill.billNo,
      bill.stateInfo.label,
      PENDING_CATEGORY_LABELS[bill.state] || '',
      ORDER_TYPE_LABELS[bill.type] || bill.type || '',
      bill.tableLabel || '',
      bill.customerName,
      bill.customerPhone,
      bill.total,
      describePayments(bill, (v) => plainAmount(v)),
      bill.paid,
      bill.balance,
      bill.tax,
      bill.discount,
      bill.charges,
      bill.subtotal,
      formatDateTime(bill.orderTime, timeZone),
      formatDateTime(bill.closedAt, timeZone),
      staffName(bill.serverId),
      staffName(bill.settledById),
    ]),
  ];

  const itemRows = [
    { cells: ['Bill No', 'Round', 'Item', 'Category', 'Size', 'Qty', 'Price', 'Amount', 'Item status', 'Notes'], style: 'header' },
  ];
  let itemsMissing = 0;
  bills.forEach((bill) => {
    if (!bill.items) {
      itemsMissing += 1;
      itemRows.push([bill.billNo, '', 'Items could not be loaded', '', '', null, null, null, '', '']);
      return;
    }
    groupItemsByRound(bill.items).forEach(({ round, items }) => {
      items.forEach((item) => itemRows.push([
        bill.billNo,
        round,
        item.menu_item_name || `Item #${item.menu_item}`,
        item.category_name || itemCategory(item.menu_item) || '',
        '',
        Number(item.quantity) || 0,
        money(item.unit_price ?? item.menu_item_price),
        item.status === 'cancelled' ? 0 : getItemLineAmount(item),
        item.status || '',
        item.special_instructions || '',
      ]));
    });
    itemRows.push({ cells: [bill.billNo, '', 'Items total', '', '', null, null, getItemsTotal(bill.items), '', ''], style: 'header' });
  });

  const paymentRows = [
    { cells: ['Bill No', 'Method', 'Recorded method', 'Amount', 'Payment status', 'Reference', 'Processed at', 'Processed by', 'Notes'], style: 'header' },
  ];
  bills.forEach((bill) => {
    bill.payments.forEach((p) => paymentRows.push([
      bill.billNo,
      getPaymentLabel(p),
      p.method,
      money(p.amount),
      p.status,
      getPaymentReference(p),
      formatDateTime(p.processed_at || p.created_at, timeZone),
      staffName(p.processed_by),
      p.notes || '',
    ]));
    if (bill.outstanding) {
      paymentRows.push([
        bill.billNo, 'Outstanding record', 'outstanding', money(bill.outstanding.outstanding_amount), bill.outstanding.status,
        '', formatDateTime(bill.outstanding.created_at, timeZone), bill.outstanding.resolved_by_name || '',
        [bill.outstanding.resolution_action, bill.outstanding.internal_notes].filter(Boolean).join(' | '),
      ]);
    }
  });

  if (itemsMissing) reportInfo.splice(7, 0, ['Warning', `${itemsMissing} bill(s) exported without items because they could not be loaded.`]);

  return [
    { name: 'Report Info', rows: reportInfo, columnWidths: [36, 60], moneyColumns: [] },
    { name: 'Bill Summary', rows: summaryRows, freezeRow: 1, moneyColumns: [7, 9, 10, 11, 12, 13, 14], columnWidths: [14, 18, 30, 13, 8, 20, 14, 12, 40, 12, 12, 10, 10, 10, 12, 22, 22, 18, 18] },
    { name: 'Bill Items', rows: itemRows, freezeRow: 1, moneyColumns: [6, 7], columnWidths: [14, 7, 34, 16, 8, 6, 11, 12, 12, 30] },
    { name: 'Payment Details', rows: paymentRows, freezeRow: 1, moneyColumns: [3], columnWidths: [14, 14, 16, 12, 16, 20, 22, 18, 50] },
  ];
};

export const exportHistoryToExcel = (args) => {
  const sheets = buildHistorySheets(args);
  const stamp = new Date().toISOString().slice(0, 16).replace(/[-:T]/g, '');
  const tab = args.meta.tab === 'pending' ? 'pending-bills' : 'sales-history';
  downloadXlsx(`${tab}-${args.meta.fileRange || 'report'}-${stamp}.xlsx`, sheets);
};
