CREATE TABLE app.categories (
  id               bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  tenant_id        bigint NOT NULL REFERENCES platform.tenants(id),
  parent_id        bigint,                         -- subcategories
  name             text NOT NULL,
  description      text,
  image_url        text,
  icon             text,
  default_prep_station_id bigint,
  sort_order       int NOT NULL DEFAULT 0,
  is_active        boolean NOT NULL DEFAULT true,
  created_at       timestamptz NOT NULL DEFAULT now(),
  updated_at       timestamptz NOT NULL DEFAULT now(),
  UNIQUE (tenant_id, id),
  FOREIGN KEY (tenant_id, parent_id) REFERENCES app.categories (tenant_id, id),
  FOREIGN KEY (tenant_id, default_prep_station_id) REFERENCES app.prep_stations (tenant_id, id)
);

-- Several taxes per category (Product Management -> Categories -> Taxes)
CREATE TABLE app.category_taxes (
  tenant_id    bigint NOT NULL,
  category_id  bigint NOT NULL,
  tax_id       bigint NOT NULL,
  PRIMARY KEY (tenant_id, category_id, tax_id),
  FOREIGN KEY (tenant_id, category_id) REFERENCES app.categories (tenant_id, id) ON DELETE CASCADE,
  FOREIGN KEY (tenant_id, tax_id) REFERENCES app.taxes (tenant_id, id)
);

CREATE TABLE app.products (
  id                   bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  tenant_id            bigint NOT NULL REFERENCES platform.tenants(id),
  category_id          bigint NOT NULL,
  sku                  text,
  name                 text NOT NULL,
  short_name           text,                       -- for KOT / narrow receipts
  description          text,
  product_type         text NOT NULL DEFAULT 'item' CHECK (product_type IN ('item','combo','open_price','weighted')),
  base_price           app.money NOT NULL DEFAULT 0 CHECK (base_price >= 0),
  cost_price           app.money,
  food_type            text CHECK (food_type IN ('veg','non_veg','egg','vegan')),
  is_spicy             boolean NOT NULL DEFAULT false,
  allergens            text[] NOT NULL DEFAULT '{}',
  dietary_tags         text[] NOT NULL DEFAULT '{}',
  calories             int,
  preparation_minutes  int,
  prep_station_id      bigint,                     -- NULL = category default
  uses_category_taxes  boolean NOT NULL DEFAULT true, -- false = product_taxes below
  discountable         boolean NOT NULL DEFAULT true,
  image_url            text,
  kitchen_notes        text,
  sort_order           int NOT NULL DEFAULT 0,
  is_active            boolean NOT NULL DEFAULT true, -- archived when false; never hard-deleted once sold
  created_at           timestamptz NOT NULL DEFAULT now(),
  updated_at           timestamptz NOT NULL DEFAULT now(),
  UNIQUE (tenant_id, id),
  FOREIGN KEY (tenant_id, category_id) REFERENCES app.categories (tenant_id, id),
  FOREIGN KEY (tenant_id, prep_station_id) REFERENCES app.prep_stations (tenant_id, id)
);
CREATE UNIQUE INDEX ux_products_sku ON app.products (tenant_id, lower(sku)) WHERE sku IS NOT NULL;
CREATE INDEX ix_products_category ON app.products (tenant_id, category_id);

CREATE TABLE app.product_taxes (
  tenant_id   bigint NOT NULL,
  product_id  bigint NOT NULL,
  tax_id      bigint NOT NULL,
  PRIMARY KEY (tenant_id, product_id, tax_id),
  FOREIGN KEY (tenant_id, product_id) REFERENCES app.products (tenant_id, id) ON DELETE CASCADE,
  FOREIGN KEY (tenant_id, tax_id) REFERENCES app.taxes (tenant_id, id)
);

