-- =============================================================================
-- APP: taxes (client-defined names, codes and rates)
-- =============================================================================

CREATE TABLE app.taxes (
  id              bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  tenant_id       bigint NOT NULL REFERENCES platform.tenants(id),
  outlet_id       bigint,                          -- NULL = all outlets
  name            text NOT NULL,                   -- CGST, SGST, VAT, Service Tax, Packing
  code            text,
  type            text NOT NULL CHECK (type IN ('percentage','fixed')),
  rate            app.rate,                        -- percentage taxes
  amount          app.money,                       -- fixed taxes
  fixed_basis     text CHECK (fixed_basis IN ('per_unit','per_bill')),
  channels        text[] NOT NULL DEFAULT '{}',    -- order types it applies to; empty = all
  is_compound     boolean NOT NULL DEFAULT false,  -- charged on price + earlier taxes (rare; some jurisdictions)
  sequence        smallint NOT NULL DEFAULT 0,     -- calculation order for compound taxes
  reporting_code  text,                            -- HSN / SAC
  is_active       boolean NOT NULL DEFAULT true,
  valid_from      date,
  valid_to        date,
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now(),
  UNIQUE (tenant_id, id),
  FOREIGN KEY (tenant_id, outlet_id) REFERENCES app.outlets (tenant_id, id),
  CHECK ((type = 'percentage' AND rate IS NOT NULL AND rate BETWEEN 0 AND 100 AND amount IS NULL AND fixed_basis IS NULL)
      OR (type = 'fixed' AND amount IS NOT NULL AND amount >= 0 AND fixed_basis IS NOT NULL AND rate IS NULL))
);
CREATE UNIQUE INDEX ux_taxes_name ON app.taxes (tenant_id, coalesce(outlet_id, 0), lower(name));

