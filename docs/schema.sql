-- A restaurant / cafe / bar of the client. A client can have many.
CREATE TABLE app.outlets (
  id                bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  tenant_id         bigint NOT NULL REFERENCES platform.tenants(id),
  code              text NOT NULL,                 -- short code used in invoice prefixes
  name              text NOT NULL,
  type              text NOT NULL DEFAULT 'restaurant'
                    CHECK (type IN ('restaurant','cafe','bar','qsr','bakery','room_service','poolside','banquet','cloud_kitchen','other')),
  description       text,
  address           text,
  city              text,
  state_code        text,                          -- needed for GST place of supply
  postal_code       text,
  phone             text,
  email             text,
  tax_reg_number    text,                          -- outlet GSTIN / TRN (may differ per state)
  licence_label     text,                          -- FSSAI Lic. No
  licence_number    text,
  currency_code     char(3) REFERENCES platform.currencies(code),  -- NULL = client currency
  timezone          text,                                         -- NULL = client timezone
  day_close_time    time NOT NULL DEFAULT '04:00', -- business day rolls over here
  opening_hours     jsonb NOT NULL DEFAULT '{}',
  capacity          int,
  settings          jsonb NOT NULL DEFAULT '{}',   -- service charge, rounding, QR mode, discount limit...
  is_active         boolean NOT NULL DEFAULT true,
  sort_order        int NOT NULL DEFAULT 0,
  created_at        timestamptz NOT NULL DEFAULT now(),
  updated_at        timestamptz NOT NULL DEFAULT now(),
  UNIQUE (tenant_id, id),
  UNIQUE (tenant_id, code)
);

-- Client-wide settings (one row per client)
CREATE TABLE app.tenant_settings (
  tenant_id              bigint PRIMARY KEY REFERENCES platform.tenants(id),
  prices_include_tax     boolean NOT NULL DEFAULT false,
  rounding_mode          text NOT NULL DEFAULT 'nearest'
                         CHECK (rounding_mode IN ('none','nearest','up','down')),
  rounding_step          app.money NOT NULL DEFAULT 1, -- round bill total to 1.00, 0.05 ...
  fiscal_year_start      smallint NOT NULL DEFAULT 4 CHECK (fiscal_year_start BETWEEN 1 AND 12),
  invoice_format         text NOT NULL DEFAULT '{outlet}/{fy}/{seq:06}',
  cashier_discount_limit app.rate NOT NULL DEFAULT 10,
  require_otp_for_admins boolean NOT NULL DEFAULT true,
  settings               jsonb NOT NULL DEFAULT '{}',
  updated_at             timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE app.roles (
  id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  tenant_id   bigint NOT NULL REFERENCES platform.tenants(id),
  key         text NOT NULL,                       -- administrator, manager, cashier, waiter, or custom
  name        text NOT NULL,
  can_login   boolean NOT NULL DEFAULT true,       -- waiters: false
  is_system   boolean NOT NULL DEFAULT false,      -- seeded roles cannot be deleted
  created_at  timestamptz NOT NULL DEFAULT now(),
  UNIQUE (tenant_id, id),
  UNIQUE (tenant_id, key)
);

CREATE TABLE app.role_permissions (
  tenant_id       bigint NOT NULL,
  role_id         bigint NOT NULL,
  permission_key  text NOT NULL REFERENCES platform.permissions(key),
  PRIMARY KEY (tenant_id, role_id, permission_key),
  FOREIGN KEY (tenant_id, role_id) REFERENCES app.roles (tenant_id, id) ON DELETE CASCADE
);

CREATE TABLE app.users (
  id                    bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  tenant_id             bigint NOT NULL REFERENCES platform.tenants(id),
  username              text NOT NULL,
  email                 text,
  phone                 text,
  first_name            text NOT NULL DEFAULT '',
  last_name             text NOT NULL DEFAULT '',
  role_id               bigint NOT NULL,
  language              text,                      -- NULL = client default
  password_hash         text,                      -- NULL = cannot sign in (waiters)
  pin_hash              text,                      -- short approval PIN for managers
  must_change_password  boolean NOT NULL DEFAULT true,
  is_active             boolean NOT NULL DEFAULT true,
  failed_logins         int NOT NULL DEFAULT 0,
  locked_until          timestamptz,
  last_login_at         timestamptz,
  password_changed_at   timestamptz,
  created_by            bigint,
  created_at            timestamptz NOT NULL DEFAULT now(),
  updated_at            timestamptz NOT NULL DEFAULT now(),
  UNIQUE (tenant_id, id),
  FOREIGN KEY (tenant_id, role_id) REFERENCES app.roles (tenant_id, id)
);
-- Login IDs are unique across ALL clients: one login page, the login ID finds the client
CREATE UNIQUE INDEX ux_users_login_id ON app.users (lower(username));
CREATE UNIQUE INDEX ux_users_email ON app.users (tenant_id, lower(email)) WHERE email IS NOT NULL;

-- Per-user changes on top of the role (Edit user -> Access)
CREATE TABLE app.user_permission_overrides (
  tenant_id       bigint NOT NULL,
  user_id         bigint NOT NULL,
  permission_key  text NOT NULL REFERENCES platform.permissions(key),
  granted         boolean NOT NULL,                -- true = add, false = remove
  PRIMARY KEY (tenant_id, user_id, permission_key),
  FOREIGN KEY (tenant_id, user_id) REFERENCES app.users (tenant_id, id) ON DELETE CASCADE
);

-- Which outlets a user may work in (no rows = all outlets)
CREATE TABLE app.user_outlets (
  tenant_id  bigint NOT NULL,
  user_id    bigint NOT NULL,
  outlet_id  bigint NOT NULL,
  PRIMARY KEY (tenant_id, user_id, outlet_id),
  FOREIGN KEY (tenant_id, user_id) REFERENCES app.users (tenant_id, id) ON DELETE CASCADE,
  FOREIGN KEY (tenant_id, outlet_id) REFERENCES app.outlets (tenant_id, id) ON DELETE CASCADE
);

-- Refresh tokens (rotated; revoked on logout, password change or client suspension)
CREATE TABLE app.auth_sessions (
  id            bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  tenant_id     bigint NOT NULL REFERENCES platform.tenants(id),
  user_id       bigint NOT NULL,
  token_hash    text NOT NULL UNIQUE,
  device_id     bigint,
  user_agent    text,
  ip_address    inet,
  expires_at    timestamptz NOT NULL,
  revoked_at    timestamptz,
  created_at    timestamptz NOT NULL DEFAULT now(),
  UNIQUE (tenant_id, id),
  FOREIGN KEY (tenant_id, user_id) REFERENCES app.users (tenant_id, id) ON DELETE CASCADE
);

-- Emailed sign-in codes and trusted devices (the POS login OTP step)
CREATE TABLE app.otp_challenges (
  id            bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  tenant_id     bigint NOT NULL REFERENCES platform.tenants(id),
  user_id       bigint NOT NULL,
  code_hash     text NOT NULL,
  attempts      int NOT NULL DEFAULT 0,
  expires_at    timestamptz NOT NULL,
  consumed_at   timestamptz,
  created_at    timestamptz NOT NULL DEFAULT now(),
  FOREIGN KEY (tenant_id, user_id) REFERENCES app.users (tenant_id, id) ON DELETE CASCADE
);

CREATE TABLE app.trusted_devices (
  id            bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  tenant_id     bigint NOT NULL REFERENCES platform.tenants(id),
  user_id       bigint NOT NULL,
  trust_hash    text NOT NULL UNIQUE,
  expires_at    timestamptz NOT NULL,
  created_at    timestamptz NOT NULL DEFAULT now(),
  FOREIGN KEY (tenant_id, user_id) REFERENCES app.users (tenant_id, id) ON DELETE CASCADE
);

-- POS terminals, kitchen displays and print companions registered to an outlet
CREATE TABLE app.devices (
  id            bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  tenant_id     bigint NOT NULL REFERENCES platform.tenants(id),
  outlet_id     bigint NOT NULL,
  name          text NOT NULL,
  kind          text NOT NULL DEFAULT 'pos' CHECK (kind IN ('pos','kds','printer','waiter_app','kiosk')),
  device_key    text NOT NULL UNIQUE,              -- generated on registration
  settings      jsonb NOT NULL DEFAULT '{}',       -- device print overrides, paper size
  last_seen_at  timestamptz,
  is_active     boolean NOT NULL DEFAULT true,
  created_at    timestamptz NOT NULL DEFAULT now(),
  UNIQUE (tenant_id, id),
  FOREIGN KEY (tenant_id, outlet_id) REFERENCES app.outlets (tenant_id, id)
);

-- Manager approvals: single use, short-lived, kept for the audit trail
CREATE TABLE app.approvals (
  id               bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  tenant_id        bigint NOT NULL REFERENCES platform.tenants(id),
  public_id        uuid NOT NULL DEFAULT gen_random_uuid() UNIQUE,
  outlet_id        bigint,
  permission_key   text NOT NULL REFERENCES platform.permissions(key),
  approver_id      bigint NOT NULL,
  requested_by     bigint NOT NULL,
  order_id         bigint,
  context          jsonb NOT NULL DEFAULT '{}',
  expires_at       timestamptz NOT NULL,
  used_at          timestamptz,
  created_at       timestamptz NOT NULL DEFAULT now(),
  UNIQUE (tenant_id, id),
  FOREIGN KEY (tenant_id, approver_id) REFERENCES app.users (tenant_id, id),
  FOREIGN KEY (tenant_id, requested_by) REFERENCES app.users (tenant_id, id),
  FOREIGN KEY (tenant_id, outlet_id) REFERENCES app.outlets (tenant_id, id)
);

