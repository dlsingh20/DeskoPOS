-- Tax summary per bill (printed bill, History, Reports -> Tax summary)
CREATE VIEW app.v_order_tax_breakdown WITH (security_invoker = true) AS
SELECT oi.tenant_id, oi.order_id, t.tax_code, t.tax_name, t.rate,
       sum(t.taxable_amount) AS taxable_amount, sum(t.tax_amount) AS tax_amount
FROM app.order_item_taxes t
JOIN app.order_items oi ON oi.tenant_id = t.tenant_id AND oi.id = t.order_item_id
WHERE oi.status <> 'cancelled'
GROUP BY oi.tenant_id, oi.order_id, t.tax_code, t.tax_name, t.rate
UNION ALL
SELECT tenant_id, order_id, tax_code, tax_name, NULL, NULL, tax_amount
FROM app.order_taxes;

-- =============================================================================
-- updated_at triggers
-- =============================================================================

DO $$
DECLARE r record;
BEGIN
  FOR r IN
    SELECT c.table_name FROM information_schema.columns c
    JOIN information_schema.tables t ON t.table_schema = c.table_schema AND t.table_name = c.table_name
    WHERE c.table_schema = 'app' AND c.column_name = 'updated_at' AND t.table_type = 'BASE TABLE'
  LOOP
    EXECUTE format('CREATE TRIGGER trg_%s_updated BEFORE UPDATE ON app.%I FOR EACH ROW EXECUTE FUNCTION app.touch_updated_at()', r.table_name, r.table_name);
  END LOOP;
END $$;

-- =============================================================================
-- Row Level Security: a client session only ever sees its own rows
-- =============================================================================

DO $$
DECLARE r record;
BEGIN
  FOR r IN
    SELECT c.table_name FROM information_schema.columns c
    JOIN information_schema.tables t ON t.table_schema = c.table_schema AND t.table_name = c.table_name
    WHERE c.table_schema = 'app' AND c.column_name = 'tenant_id' AND t.table_type = 'BASE TABLE'
  LOOP
    EXECUTE format('ALTER TABLE app.%I ENABLE ROW LEVEL SECURITY', r.table_name);
    EXECUTE format('ALTER TABLE app.%I FORCE ROW LEVEL SECURITY', r.table_name);
    EXECUTE format(
      'CREATE POLICY tenant_isolation ON app.%I USING (tenant_id = app.current_tenant_id()) WITH CHECK (tenant_id = app.current_tenant_id())',
      r.table_name);
  END LOOP;
END $$;

-- The signed-in client's own record (status, currency, locale, features).
-- pos_api cannot read platform.tenants directly, so it never sees other clients.
CREATE OR REPLACE FUNCTION app.current_tenant()
RETURNS TABLE (id bigint, name text, status text, country_code char(2), currency_code char(3),
               locale text, timezone text, plan_features jsonb, feature_overrides jsonb)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = pg_catalog, platform AS $$
  SELECT t.id, t.name, t.status, t.country_code, t.currency_code, t.locale, t.timezone,
         coalesce(p.features, '{}'), t.feature_overrides
  FROM platform.tenants t LEFT JOIN platform.plans p ON p.id = t.plan_id
  WHERE t.id = app.current_tenant_id()
$$;

-- Sign-in: find the client from the login ID alone. Runs before any client is
-- known, so it is SECURITY DEFINER and returns only what the login check needs.
CREATE OR REPLACE FUNCTION app.lookup_login(p_login text)
RETURNS TABLE (tenant_id bigint, tenant_status text, user_id bigint, password_hash text,
               is_active boolean, can_login boolean, locked_until timestamptz)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = pg_catalog, app, platform AS $$
  SELECT u.tenant_id, t.status, u.id, u.password_hash, u.is_active, r.can_login, u.locked_until
  FROM app.users u
  JOIN platform.tenants t ON t.id = u.tenant_id
  JOIN app.roles r ON r.tenant_id = u.tenant_id AND r.id = u.role_id
  WHERE lower(u.username) = lower(p_login)
$$;

-- Database roles (passwords are set by deployment, not here):
--   pos_api       the POS API. Subject to RLS.
--   pos_platform  the Super Admin console API. BYPASSRLS, used only to
--                 provision and support clients; every use is audited.
--   pos_migrator  owns the schema; runs migrations.
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'pos_api') THEN
    CREATE ROLE pos_api NOLOGIN NOBYPASSRLS;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'pos_platform') THEN
    CREATE ROLE pos_platform NOLOGIN BYPASSRLS;
  END IF;
END $$;

