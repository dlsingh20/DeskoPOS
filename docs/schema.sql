-- =============================================================================
-- AppDesko POS - independent multi-tenant PostgreSQL schema (PostgreSQL 15+)
--
-- Two schemas:
--   platform  Super Admin console: clients (tenants), plans, platform users,
--             global reference data. Not visible to client logins.
--   app       Everything a client owns: outlets, users, products, taxes,
--             orders, payments, cash counters, inventory, settings.
--
-- Tenancy rules (see DESIGN.md, "Multi-tenancy"):
--   * Every app table has tenant_id NOT NULL.
--   * Every app table has UNIQUE (tenant_id, id); every reference between app
--     tables is a composite FK (tenant_id, x_id), so a row can never point at
--     another client's row, even through a bug.
--   * Row Level Security filters every app table on the session setting
--     app.tenant_id, set by the API per request (SET LOCAL app.tenant_id = ..).
--   * Status / type columns are text + CHECK, not PG enums, so new values
--     ship as a simple constraint change.
-- Money is numeric(18,4) and rounded to the currency's decimals by the API.
-- =============================================================================

CREATE SCHEMA IF NOT EXISTS platform;
CREATE SCHEMA IF NOT EXISTS app;

-- ---------------------------------------------------------------------------
-- Shared helpers
-- ---------------------------------------------------------------------------

CREATE DOMAIN app.money AS numeric(18,4);
CREATE DOMAIN app.qty   AS numeric(12,3);
CREATE DOMAIN app.rate  AS numeric(9,4);   -- percentages, 0-100

CREATE OR REPLACE FUNCTION app.current_tenant_id() RETURNS bigint
LANGUAGE sql STABLE AS $$
  SELECT nullif(current_setting('app.tenant_id', true), '')::bigint
$$;

CREATE OR REPLACE FUNCTION app.touch_updated_at() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END $$;

-- =============================================================================
-- PLATFORM (Super Admin)
-- =============================================================================

CREATE TABLE platform.currencies (
  code        char(3) PRIMARY KEY,                 -- ISO 4217
  name        text NOT NULL,
  symbol      text NOT NULL,
  decimals    smallint NOT NULL DEFAULT 2 CHECK (decimals BETWEEN 0 AND 4)
);

CREATE TABLE platform.countries (
  code              char(2) PRIMARY KEY,           -- ISO 3166-1 alpha-2
  name              text NOT NULL,
  default_currency  char(3) NOT NULL REFERENCES platform.currencies(code),
  default_locale    text NOT NULL,                 -- en-IN, ar-AE, en-US
  default_timezone  text NOT NULL,                 -- Asia/Kolkata
  tax_id_label      text,                          -- GSTIN, TRN, VAT No
  tax_template      jsonb NOT NULL DEFAULT '[]'    -- taxes seeded for a new client
);

-- Subscription plans: limits and feature switches sold to clients
CREATE TABLE platform.plans (
  id            bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  code          text NOT NULL UNIQUE,              -- starter, growth, enterprise
  name          text NOT NULL,
  max_outlets   int,                               -- NULL = unlimited
  max_users     int,
  max_devices   int,
  features      jsonb NOT NULL DEFAULT '{}',       -- {"inventory": true, "qr_ordering": false}
  is_active     boolean NOT NULL DEFAULT true,
  created_at    timestamptz NOT NULL DEFAULT now()
);

-- A client (restaurant / cafe business). id is the public Client ID, from 101.
CREATE TABLE platform.tenants (
  id                bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 101) PRIMARY KEY,
  name              text NOT NULL,                 -- legal / display name
  business_type     text NOT NULL DEFAULT 'restaurant'
                    CHECK (business_type IN ('restaurant','cafe','bar','qsr','bakery','food_court','cloud_kitchen','hotel_fnb','other')),
  status            text NOT NULL DEFAULT 'pending'
                    CHECK (status IN ('pending','active','suspended','closed')),
  country_code      char(2) NOT NULL REFERENCES platform.countries(code),
  currency_code     char(3) NOT NULL REFERENCES platform.currencies(code),
  locale            text NOT NULL,
  timezone          text NOT NULL,
  language          text NOT NULL DEFAULT 'en',  -- default UI language for the client's users
  plan_id           bigint REFERENCES platform.plans(id),
  feature_overrides jsonb NOT NULL DEFAULT '{}',   -- per-client switches on top of the plan
  contact_name      text,
  contact_email     text,
  contact_phone     text,
  billing_address   text,
  tax_reg_number    text,                          -- client's own GSTIN / TRN
  login_prefix      text UNIQUE,                   -- suggested start of login IDs: sg -> sg_admin
  trial_ends_at     timestamptz,
  activated_at      timestamptz,
  suspended_at      timestamptz,
  suspended_reason  text,
  closed_at         timestamptz,
  created_by        bigint,                        -- platform.platform_users
  created_at        timestamptz NOT NULL DEFAULT now(),
  updated_at        timestamptz NOT NULL DEFAULT now()
);
CREATE TRIGGER trg_tenants_updated BEFORE UPDATE ON platform.tenants
  FOR EACH ROW EXECUTE FUNCTION app.touch_updated_at();

CREATE TABLE platform.tenant_status_history (
  id           bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  tenant_id    bigint NOT NULL REFERENCES platform.tenants(id),
  from_status  text,
  to_status    text NOT NULL,
  reason       text,
  changed_by   bigint NOT NULL,                    -- platform user
  changed_at   timestamptz NOT NULL DEFAULT now()
);

-- Super Admin console users (AppDesko staff). Separate from client users.
CREATE TABLE platform.platform_users (
  id              bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  email           text NOT NULL,
  full_name       text NOT NULL,
  password_hash   text NOT NULL,                   -- argon2id
  mfa_secret      text,                            -- TOTP, encrypted at rest; required
  role            text NOT NULL DEFAULT 'support'
                  CHECK (role IN ('owner','admin','support','billing','read_only')),
  is_active       boolean NOT NULL DEFAULT true,
  last_login_at   timestamptz,
  created_at      timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX ux_platform_users_email ON platform.platform_users (lower(email));

-- Support access to a client's data: time-boxed, with a reason, always audited
CREATE TABLE platform.support_sessions (
  id                bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  platform_user_id  bigint NOT NULL REFERENCES platform.platform_users(id),
  tenant_id         bigint NOT NULL REFERENCES platform.tenants(id),
  reason            text NOT NULL,
  read_only         boolean NOT NULL DEFAULT true,
  started_at        timestamptz NOT NULL DEFAULT now(),
  expires_at        timestamptz NOT NULL,
  ended_at          timestamptz
);

CREATE TABLE platform.platform_audit_log (
  id                bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  platform_user_id  bigint REFERENCES platform.platform_users(id),
  tenant_id         bigint REFERENCES platform.tenants(id),
  action            text NOT NULL,                 -- tenant.create, tenant.suspend, admin.reset_password
  details           jsonb NOT NULL DEFAULT '{}',
  ip_address        inet,
  created_at        timestamptz NOT NULL DEFAULT now()
);

-- Permission catalogue (same for every client; roles pick from it)
CREATE TABLE platform.permissions (
  key          text PRIMARY KEY,                   -- bill.settle, discount.unlimited
  group_name   text NOT NULL,
  label        text NOT NULL,
  approvable   boolean NOT NULL DEFAULT false,     -- can be done with a manager approval
  admin_only   boolean NOT NULL DEFAULT false,
  sort_order   int NOT NULL DEFAULT 0
);

-- =============================================================================
-- APP: organisation, users and access
